#!/usr/bin/env python3
"""Emit proposed leading-coefficient rows with kernel-checked transition proofs.
Python is a source generator only. Every emitted numerical equality is proved by
ordinary Lean `decide`; correctness comes from certify_top_row.
"""
from pathlib import Path
from math import comb
import json
import argparse

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="compare generated sources without writing")
args = parser.parse_args()

root = Path(__file__).resolve().parent.parent
out = root / 'RestrictedBell' / 'ComputedRows'
out.mkdir(exist_ok=True)
rows = [[1] + [0]*38]
for n in range(1, 801):
    rows.append([sum(comb(n-1,j)*rows[n-1-j][r-j]
                     for j in range(min(5,n)) if j <= r) if r < n else 0
                 for r in range(39)])
cert = json.loads((root/'crosscheck/independent-certificate.json').read_text())
assert rows[800] == cert['top_coefficients']
for batch in range(9):
    low, high = batch*100, min(801,(batch+1)*100)
    previous = 'RestrictedBell.TopRecurrence' if batch == 0 else f'RestrictedBell.ComputedRows.Batch{batch-1}'
    text = f'''-- Generated by scripts/generate_rows.py. Values are proposals, checked below.
import {previous}
namespace RestrictedBell.ComputedRows
set_option maxRecDepth 100000
set_option maxHeartbeats 0
'''
    for n in range(low,high):
        text += f'\ndef row{n} : List ℕ := [' + ', '.join(map(str,rows[n])) + ']\n'
        text += f'\ntheorem row{n}_correct : ∀ r < 39, row{n}[r]?.getD 0 = top {n} r := by\n'
        if n == 0:
            text += '''  intro r hr
  rw [top_zero]
  have h : ∀ r : Fin 39, row0[r.val]?.getD 0 = if r.val = 0 then 1 else 0 := by decide
  exact h ⟨r, hr⟩
'''
        else:
            branches = ' | '.join(f'{j} => row{max(0,n-1-j)}' for j in range(4)) + f' | _ => row{max(0,n-5)}'
            text += f'''  apply certify_top_row {n} (by decide) row{n} (fun j => match j with | {branches})
  · intro j hj
    have hj' : j < {min(5,n)} := by simpa using hj
    interval_cases j
'''
            for j in range(min(5,n)):
                text += f'    · exact row{n-1-j}_correct\n'
            text += '  · decide\n'
    text += '\nend RestrictedBell.ComputedRows\n'
    path = out/f'Batch{batch}.lean'
    if args.check:
        assert path.read_text() == text, path
    else:
        path.write_text(text)
print(('Checked' if args.check else 'Generated') + ' 801 proposed rows, in 9 compilation batches.')
